export function csesDifficulty(id) {
  const entry = CSES[id];
  if (!entry) return null;
  const [solvers, code] = entry;
  return { level: BY_CODE[code], detail: `solved by ${solvers.toLocaleString('en-US')} on CSES` };
}

export function cfDifficulty(code) {
  const rating = CF[code];
  if (!rating) return null;
  const i = CF_BANDS.findIndex((top) => rating <= top);
  return { level: LEVELS[i === -1 ? LEVELS.length - 1 : i], detail: `rated ${rating} on Codeforces` };
}
